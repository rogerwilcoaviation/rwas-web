import assert from 'node:assert/strict';
import fs from 'node:fs';
import test from 'node:test';
import {
  OTC_RETAIL_PRODUCTS,
  PUBLIC_PRICE_AUTHORITIES,
  POLICY_DESCRIPTIONS,
  POLICY_SOURCE,
  buildAudit,
  applyAudit,
} from './reconcile-garmin-otc-retail.mjs';
import {
  OPERATOR_CONFIRMED_CERTIFIED_OTC,
  POLICY_REVIEWED_CERTIFIED_OTC,
  APPROVED_CERTIFIED_OTC,
  isExactCertifiedOtc,
  normalizeRetailTags,
  auditState,
} from './reconcile-garmin-catalog-placement.mjs';
import {
  approvedPublicPrice,
  assertReviewedCommercialWrites,
} from './garmin-commercial-review.mjs';

// Reviewed contract, not a snapshot regenerated by the test. Changes require
// another exact-SKU review, especially authority and non-manufacturer prices.
const fixture = JSON.parse(
  fs.readFileSync(
    new URL('../tests/garmin/september-retail-contract.json', import.meta.url),
  ),
);
const collection = { id: 'fixture-retail', handle: 'avionics-certified' };
const staleCache = {
  rows: Object.fromEntries(
    fixture.products.map(({ policy }) => [
      policy.sku,
      { list_price: 9999, source: 'stale fixture' },
    ]),
  ),
};
function productFor(policy) {
  return {
    id: policy.productId,
    handle: policy.handle,
    title: policy.family,
    status: 'ACTIVE',
    productType: 'Avionics — Certified',
    vendor: 'Garmin',
    tags: ['garmin', 'otc-disabled', 'garmin-dealer-only', 'keep-me'],
    descriptionHtml:
      '<p>Existing compatibility and installation restrictions.</p>',
    dealerOnly: { id: 'fixture-metafield', value: 'true' },
    collections: { nodes: [collection] },
    variants: {
      nodes: [{ id: policy.variantId, sku: policy.sku, price: '9999.00' }],
    },
  };
}
function normalizedTags(product) {
  const record = {
    currentStatus: product.status,
    currentProductType: product.productType,
    sku: product.variants.nodes[0]?.sku,
    nextTags: [...product.tags],
  };
  normalizeRetailTags(record, product);
  return record.nextTags;
}

test('September exact-SKU contracts and mocked reconciliation', async (t) => {
  const originalFetch = globalThis.fetch;
  const envKeys = [
    'SHOPIFY_STORE_DOMAIN',
    'SHOPIFY_ADMIN_TOKEN',
    'SHOPIFY_ADMIN_API_TOKEN',
    'SHOPIFY_API_VERSION',
  ];
  const originalEnv = Object.fromEntries(
    envKeys.map((key) => [key, process.env[key]]),
  );
  let products = [];
  const writes = [];
  process.env.SHOPIFY_STORE_DOMAIN = 'offline-fixture.invalid';
  process.env.SHOPIFY_ADMIN_TOKEN = 'offline-fixture';
  process.env.SHOPIFY_API_VERSION = '2026-01';
  globalThis.fetch = async (url, init) => {
    assert.equal(
      url,
      'https://offline-fixture.invalid/admin/api/2026-01/graphql.json',
    );
    const { query, variables } = JSON.parse(init.body);
    let data;
    if (query.includes('query ProductBySku')) {
      data = { products: { nodes: products } };
    } else {
      const field = query.includes('mutation ReconcileOtcProduct')
        ? 'productUpdate'
        : query.includes('mutation ReconcileOtcPrice')
          ? 'productVariantsBulkUpdate'
          : query.includes('mutation DeleteDealerOnlyMetafield')
            ? 'metafieldsDelete'
            : null;
      assert.ok(field, 'Unexpected request: no real network is allowed');
      writes.push({ field, variables });
      data = { [field]: { userErrors: [] } };
    }
    return new Response(JSON.stringify({ data }), { status: 200 });
  };
  try {
    assert.deepEqual(POLICY_SOURCE, fixture.policySource);
    assert.equal(fixture.products.length, 16);
    assert.equal(
      new Set(fixture.products.map(({ policy }) => policy.sku)).size,
      16,
    );
    for (const expected of fixture.products) {
      const { policy, price, descriptionHtml, retailAuthority } = expected;
      await t.test(policy.sku, async () => {
        const currentPolicies = OTC_RETAIL_PRODUCTS.filter(
          (p) => p.sku === policy.sku,
        );
        assert.deepEqual(currentPolicies, [policy]);
        assert.deepEqual(PUBLIC_PRICE_AUTHORITIES[policy.sku], price);
        assert.equal(POLICY_DESCRIPTIONS[policy.sku] ?? null, descriptionHtml);
        assert.equal(
          approvedPublicPrice(policy.sku),
          undefined,
          'A different price policy must not shadow the reviewed provenance',
        );
        assertReviewedCommercialWrites([policy.sku]);
        assert.equal(
          APPROVED_CERTIFIED_OTC.has(policy.sku),
          false,
          'These exceptions are not manufacturer OTC-shading approvals',
        );
        const registry =
          retailAuthority === 'operator-exception'
            ? OPERATOR_CONFIRMED_CERTIFIED_OTC
            : POLICY_REVIEWED_CERTIFIED_OTC;
        assert.deepEqual(
          registry.filter((p) => p.sku === policy.sku),
          [
            {
              sku: policy.sku,
              productId: policy.productId,
              variantId: policy.variantId,
              handle: policy.handle,
            },
          ],
        );
        const product = productFor(policy);
        products = [product];
        assert.equal(isExactCertifiedOtc(product), true);
        assert.ok(normalizedTags(product).includes('otc-eligible'));
        assert.ok(normalizedTags(product).includes('keep-me'));
        const [record] = await buildAudit(staleCache, collection, [
          currentPolicies[0],
        ]);
        assert.equal(record.state, 'changes-required');
        assert.equal(record.expectedPrice, Number(price.list_price).toFixed(2));
        assert.equal(record.productId, policy.productId);
        assert.equal(record.variantId, policy.variantId);
        assert.equal(record.handle, policy.handle);
        assert.equal(record.eligibilityAuthority, policy.eligibilityAuthority);
        assert.equal(record.catalogObservation, policy.catalogObservation);
        assert.equal(record.changes.description, descriptionHtml !== null);
        assert.ok(record.nextTags.includes('otc-eligible'));
        assert.ok(!record.nextTags.includes('garmin-dealer-only'));
        assert.ok(!record.nextTags.includes('otc-disabled'));
        const rendered = structuredClone(product);
        rendered.tags = record.nextTags;
        rendered.variants.nodes[0].price = record.expectedPrice;
        const audit = auditState([rendered], new Map()).summary;
        assert.ok(!audit.retailUnexpectedSkus.includes(policy.sku));
        assert.ok(!audit.retailMissingSkus.includes(policy.sku));
        writes.length = 0;
        assert.equal(await applyAudit([record], collection), 1);
        const productWrite = writes.find((w) => w.field === 'productUpdate')
          .variables.product;
        assert.equal(productWrite.id, policy.productId);
        if (descriptionHtml === null) {
          assert.ok(
            !Object.hasOwn(productWrite, 'descriptionHtml'),
            'Retain existing customer restrictions when no replacement is authorized',
          );
        } else {
          assert.equal(productWrite.descriptionHtml, descriptionHtml);
        }
        assert.deepEqual(
          writes.find((w) => w.field === 'productVariantsBulkUpdate').variables,
          {
            productId: policy.productId,
            variants: [{ id: policy.variantId, price: record.expectedPrice }],
          },
        );

        const mutations = [
          [
            'product ID',
            (p) => {
              p.id += '-duplicate';
            },
          ],
          [
            'handle',
            (p) => {
              p.handle += '-related';
            },
          ],
          [
            'variant ID',
            (p) => {
              p.variants.nodes[0].id += '-duplicate';
            },
          ],
          [
            'related SKU',
            (p) => {
              p.variants.nodes[0].sku += '-related';
            },
          ],
          [
            'extra variant',
            (p) => {
              p.variants.nodes.push({ ...p.variants.nodes[0], id: 'other' });
            },
          ],
          [
            'archived',
            (p) => {
              p.status = 'ARCHIVED';
            },
          ],
        ];
        for (const [label, mutate] of mutations) {
          const altered = structuredClone(product);
          mutate(altered);
          products = [altered];
          assert.ok(!normalizedTags(altered).includes('otc-eligible'), label);
          if (label !== 'archived')
            assert.equal(isExactCertifiedOtc(altered), false, label);
          const [rejected] = await buildAudit(staleCache, collection, [
            currentPolicies[0],
          ]);
          assert.ok(
            ['ambiguous-sku', 'missing-storefront-product'].includes(
              rejected.state,
            ),
            label,
          );
          writes.length = 0;
          assert.equal(await applyAudit([rejected], collection), 0, label);
          assert.equal(writes.length, 0, label);
          if (label !== 'archived' && label !== 'related SKU') {
            altered.tags = ['otc-eligible'];
            altered.variants.nodes[0].price = record.expectedPrice;
            const rejectedAudit = auditState([altered], new Map()).summary;
            assert.ok(
              rejectedAudit.retailUnexpectedSkus.includes(policy.sku),
              label,
            );
            assert.ok(
              rejectedAudit.retailMissingSkus.includes(policy.sku),
              label,
            );
          }
        }
        products = [product, { ...structuredClone(product), id: 'duplicate' }];
        const [duplicate] = await buildAudit(staleCache, collection, [
          currentPolicies[0],
        ]);
        assert.equal(duplicate.state, 'ambiguous-sku');
        assert.equal(await applyAudit([duplicate], collection), 0);
      });
    }
  } finally {
    globalThis.fetch = originalFetch;
    for (const key of envKeys) {
      if (originalEnv[key] === undefined) delete process.env[key];
      else process.env[key] = originalEnv[key];
    }
  }
});

test('conflicting evidence and operator price disclaimers remain explicit', () => {
  const bySku = Object.fromEntries(
    fixture.products.map((entry) => [entry.policy.sku, entry]),
  );
  assert.match(
    bySku['011-03258-00'].policy.catalogObservation,
    /not green OTC-shaded/,
  );
  assert.match(
    bySku['011-03258-00'].policy.catalogObservation,
    /210\/510 remains installation-policy included/,
  );
  assert.match(
    bySku['330-00408-62'].policy.catalogObservation,
    /No independent current manufacturer catalog OTC designation/,
  );
  for (const sku of [
    '330-00408-62',
    '011-01169-01',
    '310-00196-00',
    '330-90006-02',
  ]) {
    assert.equal(bySku[sku].price.priceType, 'Operator-confirmed retail');
    assert.match(
      bySku[sku].price.source,
      /not independently manufacturer-verified/,
    );
  }
  const connector = bySku['330-00408-62'].descriptionHtml;
  assert.match(connector, /special-order item/);
  assert.match(connector, /phone order/);
  assert.match(
    connector,
    /does not represent on-hand stock or a delivery estimate/,
  );
  assert.match(connector, /must be confirmed separately/);
  assert.match(
    bySku['011-02977-01'].descriptionHtml,
    /does not make a separate claim about the kit's individual contents/,
  );
  assert.match(
    bySku['011-01169-01'].descriptionHtml,
    /does not include a connector, backshell, contacts/,
  );
  for (const sku of ['336-00022-00', '336-00055-00']) {
    assert.match(bySku[sku].descriptionHtml, /quantity 1 adds one contact/);
    assert.match(bySku[sku].descriptionHtml, /not a pack or connector kit/);
    assert.match(
      bySku[sku].descriptionHtml,
      /wire size, tooling, and connector compatibility/,
    );
  }
  for (const sku of ['011-00950-01', '011-00950-02', '011-00950-03']) {
    assert.match(bySku[sku].descriptionHtml, /Sold individually/);
    assert.match(
      bySku[sku].descriptionHtml,
      /Confirm connector size and compatibility/,
    );
  }
  for (const sku of [
    '011-00950-04',
    '011-03258-01',
    '011-02977-00',
    '330-00408-61',
    '325-00122-01',
    '310-00196-01',
  ]) {
    assert.ok(!OTC_RETAIL_PRODUCTS.some((p) => p.sku === sku));
    assert.equal(PUBLIC_PRICE_AUTHORITIES[sku], undefined);
    assert.equal(
      isExactCertifiedOtc(productFor({ ...bySku['011-03258-00'].policy, sku })),
      false,
    );
  }
});
