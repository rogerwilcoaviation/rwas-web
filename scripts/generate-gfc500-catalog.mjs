#!/usr/bin/env node

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { basename, resolve } from 'node:path';

const pdfPath = process.argv[2];
const outputPath = process.argv[3] || 'lib/gfc500-certified-catalog.ts';

if (!pdfPath) {
  console.error(
    'Usage: node scripts/generate-gfc500-catalog.mjs <catalog.pdf> [output.ts]',
  );
  process.exit(1);
}

const textPath = `/tmp/${basename(pdfPath, '.pdf')}-${process.pid}.txt`;
execFileSync('pdftotext', ['-layout', resolve(pdfPath), textPath]);
const pages = readFileSync(textPath, 'utf8').split('\f');

const clean = (value) =>
  value
    .replace(/\s+/g, ' ')
    .replace(/\s+([,.;:)])/g, '$1')
    .replace(/([(])\s+/g, '$1')
    .trim();

const money = (value) => Number(value.replace(/[$,]/g, ''));

const aircraft = pages
  .map((page, pageIndex) => {
    const title = page.match(/GFC 500 -[^\n]+/)?.[0]?.trim();
    if (!title || pageIndex < 3 || pageIndex > 58) return null;

    const applicable = page.match(
      /Applicable Aircraft Models\*?([\s\S]*?)\n\s*System Pricing/,
    )?.[1];
    const pricing = page
      .split('System Pricing')[1]
      ?.split('System Configurations')[0];
    if (!applicable || !pricing) return null;

    const configurationArea =
      page.split(
        /NOTE: System Pricing above does not include an approved AHRS source[^\n]*/,
      )[1] ||
      page.split('System Configurations')[1] ||
      '';
    const configurationBlocks = [
      ...configurationArea.matchAll(/Product Number[\s\S]*?Total Price[^\n]*/g),
    ];
    const configurations = [
      ...pricing.matchAll(
        /^\s*(.+?)\s{2,}(\$[\d,]+\.\d{2})\s+(\$[\d,]+\.\d{2})\s*$/gm,
      ),
    ].map((match, configurationIndex) => {
      const name = clean(match[1]);
      const block = configurationBlocks[configurationIndex]?.[0] || '';
      const components = [
        ...block.matchAll(
          /^\s*([A-Z0-9]{3}-[A-Z0-9-]+)\s+(.+?)\s{2,}(\d+)\s+(\$[\d,]+\.\d{2})\s+(\$[\d,]+\.\d{2})\s+(\$[\d,]+\.\d{2})/gm,
        ),
      ].map((component) => ({
        sku: component[1],
        title: clean(component[2]),
        quantity: Number(component[3]),
        listPrice: money(component[4]),
      }));

      return {
        name,
        listPrice: money(match[2]),
        components,
      };
    });
    if (!configurations.length) return null;

    const modelText = clean(applicable);
    const [models, ...footnotes] = modelText.split(/(?=\*|NOTE:)/);
    const shortTitle = title.replace(/^GFC 500 -\s*/, '');

    return {
      id: `page-${pageIndex + 1}`,
      page: pageIndex + 1,
      label: shortTitle,
      models: clean(models),
      notes: clean(footnotes.join(' ')).replace(/^\*+\s*\*+/, '*'),
      configurations,
    };
  })
  .filter(Boolean);

const source = `// Generated by scripts/generate-gfc500-catalog.mjs. Do not edit manually.\n`;
const types = `export type Gfc500Component = {\n  sku: string;\n  title: string;\n  quantity: number;\n  listPrice: number;\n};\n\nexport type Gfc500Configuration = {\n  name: string;\n  listPrice: number;\n  components: Gfc500Component[];\n};\n\nexport type Gfc500Aircraft = {\n  id: string;\n  page: number;\n  label: string;\n  models: string;\n  notes: string;\n  configurations: Gfc500Configuration[];\n};\n\n`;
const data = `export const GFC500_CERTIFIED_AIRCRAFT: Gfc500Aircraft[] = ${JSON.stringify(aircraft, null, 2)};\n`;

writeFileSync(resolve(outputPath), source + types + data);
console.log(
  `Wrote ${aircraft.length} aircraft eligibility groups to ${outputPath}`,
);
