#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { imageSize } from 'image-size';
import { format } from 'prettier';

const root = new URL('../', import.meta.url);
const blog = JSON.parse(
  await readFile(new URL('public/blog-articles.json', root), 'utf8'),
);
const sources = new Set();

function collectImages(value) {
  if (typeof value === 'string') {
    if (
      value.startsWith('/') &&
      /\.(?:png|jpe?g|webp|avif|gif|svg)$/i.test(value)
    ) {
      sources.add(value);
    }
    for (const match of value.matchAll(
      /(?:!\[[^\]]*\]\((\/[^\s)]+)\)|\bsrc=["'](\/[^"']+)["'])/g,
    )) {
      sources.add((match[1] || match[2]).split('?')[0]);
    }
  } else if (Array.isArray(value)) {
    value.forEach(collectImages);
  } else if (value && typeof value === 'object') {
    Object.values(value).forEach(collectImages);
  }
}

collectImages(blog);
const dimensions = {};
for (const source of [...sources].sort()) {
  const file = new URL(`public${source}`, root);
  if (!file.href.startsWith(new URL('public/', root).href)) {
    throw new Error(`Blog image escapes public directory: ${source}`);
  }
  const { width, height } = imageSize(await readFile(file));
  if (!width || !height) {
    throw new Error(`Blog image has no intrinsic dimensions: ${source}`);
  }
  dimensions[source] = { width, height };
}
const output = new URL('data/blog-image-dimensions.ts', root);
const content = await format(
  `// Generated by scripts/generate-blog-image-dimensions.mjs during appinfo.\n// Read dimensions at build time so article rendering needs no filesystem APIs.\nexport const blogImageDimensions: Record<\n  string,\n  { width: number; height: number }\n> = ${JSON.stringify(dimensions, null, 2)};\n`,
  { parser: 'typescript', singleQuote: true },
);
if ((await readFile(output, 'utf8').catch(() => '')) !== content) {
  await writeFile(output, content);
}
console.log(
  `Blog image dimensions: ${sources.size} local images -> ${fileURLToPath(output)}`,
);
